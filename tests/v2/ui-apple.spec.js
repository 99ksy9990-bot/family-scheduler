import { test, expect } from './ui-fixture.js'

test('우리집 이름·불투명 타일·유리 아이콘·떠 있는 알약', async ({ page }) => {
  await expect(page).toHaveTitle('우리집')
  await expect(page.getByRole('heading', { name: '우리집', exact: true })).toBeVisible()
  const tile = page.locator('.house-tile').first()
  expect((await tile.boundingBox()).height).toBe(140)
  expect(await tile.locator('img').evaluate((img) => img.getBoundingClientRect().width)).toBe(56)
  const nav = page.getByRole('navigation')
  expect((await nav.boundingBox()).height).toBe(66)
  expect(page.viewportSize().height - (await nav.boundingBox()).y - 66).toBe(8)
  expect(await nav.evaluate((element) => getComputedStyle(element).backdropFilter)).toContain('blur(20px)')
  expect(await tile.evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect(nav.locator('.glass-icon')).toHaveCount(0)
  expect(await nav.locator('svg').first().evaluate((element) => element.getBoundingClientRect().width)).toBe(26)
  for (const scheme of ['light', 'dark']) {
    await page.emulateMedia({ colorScheme: scheme })
    const selected = nav.locator('[aria-current="page"]')
    await expect.poll(() => selected.evaluate((element) => getComputedStyle(element).color)).toBe('rgb(10, 132, 255)')
    expect(await selected.locator('svg').evaluate((element) => getComputedStyle(element).stroke)).toBe('rgb(10, 132, 255)')
    expect(await selected.evaluate((element) => getComputedStyle(element).backgroundColor)).toBe(scheme === 'light' ? 'rgba(120, 120, 128, 0.14)' : 'rgba(255, 255, 255, 0.12)')
  }
  await page.emulateMedia({ colorScheme: 'light' })
  expect(await tile.locator('.glass-icon').evaluate((element) => element.getBoundingClientRect().width)).toBe(66)
  expect(await tile.locator('.glass-icon').evaluate((element) => getComputedStyle(element).backgroundImage)).toContain('linear-gradient')
  await expect(page.locator('.glass-background')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: '가족', exact: true }).click()
  await expect(page.getByRole('button', { name: '일정 추가', exact: true })).toHaveCount(0)
})

test('개인 타일 시트·남은 목록·다음 시각만 강조', async ({ page }) => {
  await page.clock.runFor(500)
  await page.evaluate(() => {
    const events = JSON.parse(localStorage.getItem('family-scheduler-events'))
    events.push({ id: 'work', title: '오전 근무', date: '2026-11-05', time: '09:00', end: '11:00', member: 'p', type: 'shift' })
    events.push({ id: 'later', title: '저녁 일정', date: '2026-11-05', time: '19:00', end: '20:00', member: 'p' })
    localStorage.setItem('family-scheduler-events', JSON.stringify(events))
  })
  await page.reload()
  await expect(page.locator('.house-badge')).toHaveText('근무 중')
  await expect(page.locator('.house-row')).toHaveCount(2)
  await expect(page.locator('.house-row.next .time-start')).toHaveText('14:00')
  expect(await page.locator('.house-row.next .time-start').evaluate((element) => getComputedStyle(element).color)).not.toBe(await page.locator('.house-row:not(.next) .time-start').evaluate((element) => getComputedStyle(element).color))
  await page.locator('.house-tile').first().click()
  await expect(page.getByRole('dialog').getByRole('button', { name: /^오전 근무/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.house-tile').first()).toBeFocused()
})

test('라이트·다크와 움직임/투명도 줄이기 아이콘 대체', async ({ page, context }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  expect(await page.locator('body').evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgb(11, 11, 18)')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => page.locator('.house-tile .glass-icon').first().evaluate((element) => getComputedStyle(element).backgroundImage)).toBe('none')
  await expect.poll(() => page.locator('.house-tile').first().evaluate((element) => getComputedStyle(element).backdropFilter)).toBe('none')
  await expect.poll(() => page.locator('.house-tile').first().evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgb(28, 28, 30)')
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'no-preference' })
  const cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: 'light' }, { name: 'prefers-reduced-transparency', value: 'reduce' }] })
  await expect.poll(() => page.locator('.house-tile').first().evaluate((element) => getComputedStyle(element).backdropFilter)).toBe('none')
  await expect.poll(() => page.locator('.house-tile').first().evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect.poll(() => page.locator('.house-tile .glass-icon').first().evaluate((element) => getComputedStyle(element).backgroundImage)).toBe('none')
})
