import { test, expect } from './ui-fixture.js'

test('선택일로 추가·자정 넘는 자동 종료·고정 저장 버튼·Escape', async ({ page }) => {
  await page.getByRole('navigation').getByRole('button', { name: '달력', exact: true }).click()
  await page.getByRole('button', { name: '2026-11-12', exact: true }).click()
  await page.getByRole('button', { name: '일정 추가', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('날짜', { exact: true })).toHaveValue('2026-11-12')
  await dialog.getByLabel('시작 시간').fill('23:30')
  await expect(dialog.getByLabel('종료 시간')).toHaveValue('00:30')
  await expect(dialog.getByRole('switch', { name: '여러 날' })).toHaveAttribute('aria-checked', 'true')
  await expect(dialog.getByLabel('종료일')).toHaveValue('2026-11-13')
  await dialog.getByRole('button', { name: '매주', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '저장', exact: true })).toBeInViewport()
  await dialog.locator('.schedule-fields').evaluate((body) => { body.scrollTop = body.scrollHeight })
  await expect(dialog.getByRole('button', { name: '저장', exact: true })).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '일정 추가', exact: true })).toBeFocused()
})

test('여러 가족 선택·흑백 구분·종일 저장 형식과 반복·알림 유지', async ({ page }) => {
  await page.clock.runFor(500)
  await page.evaluate(() => {
    const profiles = JSON.parse(localStorage.getItem('family-scheduler-profiles-v1'))
    profiles.push({ id: 'q', name: '아이', type: 'child', characterId: 'little' })
    localStorage.setItem('family-scheduler-profiles-v1', JSON.stringify(profiles))
  })
  await page.reload()
  await page.getByRole('button', { name: '일정 추가', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const child = dialog.getByRole('button', { name: '아이', exact: true })
  expect(await child.locator('img').evaluate((img) => getComputedStyle(img).filter)).toContain('grayscale')
  await child.click()
  await expect(child).toHaveAttribute('aria-pressed', 'true')
  expect(await child.locator('img').evaluate((img) => getComputedStyle(img).filter)).toBe('none')
  await dialog.getByLabel('무슨 일정인가요?').fill('함께하는 종일 일정')
  await dialog.getByRole('switch', { name: '하루 종일' }).click()
  await expect(dialog.locator('input[type="time"]')).toHaveCount(0)
  await dialog.getByRole('button', { name: '매주', exact: true }).click()
  await dialog.getByRole('button', { name: '30분 전', exact: true }).click()
  await dialog.getByRole('button', { name: '저장', exact: true }).click()
  await page.clock.runFor(500)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('family-scheduler-events')).at(-1))
  expect(saved).toMatchObject({ members: ['p', 'q'], member: 'p', time: '종일', end: '', endDate: '2026-11-05', recurrence: { frequency: 'weekly', interval: 1 }, reminders: ['30-minutes'] })
})
