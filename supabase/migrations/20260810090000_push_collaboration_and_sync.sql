create or replace function public.save_household_state_v2(
  target_household_id uuid,
  next_state jsonb,
  expected_version bigint
)
returns public.household_states
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_version bigint;
  saved public.household_states;
begin
  if auth.uid() is null or not private.can_edit_household(target_household_id) then
    raise exception '이 가족 일정의 수정 권한이 없습니다.';
  end if;

  select version into current_version
  from public.household_states
  where household_id = target_household_id
  for update;

  if current_version is null then
    raise exception '가족 일정 저장소를 찾을 수 없습니다.';
  end if;
  if current_version <> expected_version then
    raise exception using errcode = '40001', message = 'SYNC_CONFLICT';
  end if;

  update public.household_states
  set state = next_state,
      version = version + 1,
      updated_at = now(),
      updated_by = auth.uid()
  where household_id = target_household_id
  returning * into saved;

  return saved;
end;
$$;

revoke all on function public.save_household_state_v2(uuid, jsonb, bigint) from public, anon;
grant execute on function public.save_household_state_v2(uuid, jsonb, bigint) to authenticated;

create or replace function public.get_push_cron_secret()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_role text;
  secret_value text;
begin
  caller_role := coalesce(current_setting('request.jwt.claim.role', true), '');
  if caller_role <> 'service_role' then
    raise exception 'forbidden';
  end if;
  select decrypted_secret into secret_value
  from vault.decrypted_secrets
  where name = 'push_cron_secret'
  order by created_at desc
  limit 1;
  return secret_value;
end;
$$;

revoke all on function public.get_push_cron_secret() from public, anon, authenticated;
grant execute on function public.get_push_cron_secret() to service_role;

